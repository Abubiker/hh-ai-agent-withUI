from settings import settings
from llm_providers import complete_with_retry, ProviderError


async def generate_cover_letter(vacancy_title: str, vacancy_description: str) -> str:
    MY_RESUME_SUMMARY = settings.resume_summary
    prompt = f"""
Напиши сопроводительное письмо для отклика на вакансию.
Мой профиль:
{MY_RESUME_SUMMARY}

Вакансия: {vacancy_title}
Описание: {vacancy_description}

КРИТИЧЕСКИЕ ПРАВИЛА (СТРОГО СОБЛЮДАТЬ):
1. ПИСАТЬ СТРОГО ТОЛЬКО НА РУССКОМ ЯЗЫКЕ! Никакого английского текста.
2. Пиши развернуто, структурировано (3-4 абзаца).
3. Стиль: живой, профессиональный, уверенный.
4. Включай в письмо перечисление моего стека и инструментов, а также конкретные достижения с цифрами из моего профиля из моего профиля.
5. Соотнеси мой опыт с тем, что требуется именно в этой вакансии.
6. НИКОГДА не выдумывай факты, которых нет в моем профиле: не приписывай мне высшее образование, языки программирования, инструменты, сертификаты или уровень английского выше указанного в профиле. Используй ТОЛЬКО то, что написано в профиле.
7. текущем месте работы — это мое ТЕКУЩЕЕ место работы, я работаю там прямо сейчас. Пиши о нем СТРОГО в настоящем времени ("сейчас работаю", "занимаюсь", "отвечаю за"). Запрещены формулировки в прошедшем времени вроде "работал", "в последнее время я работал", "на прошлом месте" — это грубая фактическая ошибка. В прошедшем времени можно писать ТОЛЬКО про предыдущем месте работы.
8. Никаких подписей в начале письма! Только в самом конце.
9. Подпись строго: "Дмитрий". Никаких "С уважением".
10. ВЫВОДИ ТОЛЬКО ТЕКСТ ПИСЬМА БЕЗ КАВЫЧЕК. Твой ответ копируется автоматически! Строго запрещены любые вводные фразы (например, "Here is a sample...", "Вот письмо:"). Ни слова, кроме самого письма.

Пример хорошего письма:
Здравствуйте!

Заинтересовала вакансия {vacancy_title}. Я Middle QA Engineer с коммерческим опытом более 3 лет, самостоятельно веду тестирование web- и API-продуктов с нуля: от анализа требований и проектирования тестовой модели до сопровождения релизов и разбора продакшн-инцидентов.

Сейчас работаю в текущем месте работы — low-code платформе автоматизации. Протестировал более 300 API-интеграций (OpenAI, Google, Microsoft, Telegram, Битрикс 24, amoCRM) и свыше 300 систем аутентификации к внешним сервисам, разработал 50+ автотестов на Playwright для критических интеграционных сценариев. До этого в предыдущем месте работы закрывал QA-часть на четырех проектах заказной разработки целиком — от требований до релиза.

Мой стек: JavaScript, Playwright, Postman, Git, Docker, PostgreSQL, REST, SOAP, XML. Веду тестовую документацию в Qase.IO и Allure TestOps: тест-кейсы, чек-листы, тест-планы. Есть опыт мобильного тестирования iOS через Xcode и тестирования верстки на адаптивность и кроссбраузерность.

Готов выполнить тестовое задание и обсудить детали на собеседовании.

Дмитрий
"""
    
    try:
        # deterministic=False: письму нужна живость, в отличие от классификатора.
        text = await complete_with_retry(prompt, deterministic=False, timeout=180)
        # Жесткая очистка от частых галлюцинаций LLM
        text = text.replace('"', '').replace("'", "")
        if "Here is" in text or "Here's" in text:
            text = text.split("\n\n", 1)[-1]
        if "Note:" in text:
            text = text.split("Note:")[0].strip()
        return text.strip()
    except ProviderError as e:
        print(f"Ошибка при обращении к модели (письмо): {e}")
        return "Здравствуйте! Прошу рассмотреть мое резюме на эту вакансию. Буду рад обсудить детали на собеседовании."

async def is_vacancy_suitable(vacancy_title: str, vacancy_description: str) -> bool:
    MY_RESUME_SUMMARY = settings.resume_summary
    prompt = f"""
Твоя задача — оценить, подходит ли вакансия под мои критерии поиска.
Мои требования и профиль (внимательно учти желаемую зарплату, локацию и стек технологий):
{MY_RESUME_SUMMARY}

ГЛАВНЫЙ ПРИНЦИП: я ищу работу тестировщиком (QA). Если вакансия — про тестирование
и обеспечение качества ПО (ручное, функциональное, API, автоматизация на JS/TS, мобильное),
то по умолчанию она мне ПОДХОДИТ (YES). Отклоняй (NO) только при ЯВНОМ, чётко написанном
в вакансии дисквалификаторе из списка ниже. Если сомневаешься или чего-то не хватает в
описании — отвечай YES: лишний отклик дешевле упущенной вакансии.

ВАЖНО ПРО ГРЕЙД: старшие позиции мне ПОДХОДЯТ. Senior, Сеньор, Старший тестировщик,
Ведущий инженер по тестированию — на такие вакансии отвечай YES, я готов пробовать себя
на них. Не отклоняй вакансию только за слово Senior или "старший" в названии.

Отклоняй (NO) ТОЛЬКО если в вакансии ПРЯМО указано что-то из этого:
- Это УПРАВЛЕНЧЕСКАЯ роль, а не работа руками. Признаки: есть прямые подчинённые,
  найм и оценка сотрудников, проведение 1-1, распределение задач по команде,
  ответственность за QA-стратегию всего департамента. Например: Team Lead, Head of QA,
  руководитель отдела/группы тестирования.
  НЕ считаются управлением и НЕ повод для отказа: ревью тестов и кода коллег,
  наставничество для младших, участие в собеседованиях, проектирование тест-планов.
  Это обычные задачи старшего инженера — таким вакансиям YES.
- Требуется опыт работы БОЛЕЕ 8 лет как жёсткое требование.
- Это вообще не про тестирование: чистая разработка (backend/frontend/mobile/DevOps),
  менеджеры, аналитики, HR, маркетологи, дизайнеры, преподаватели, продавцы, рабочие
  специальности, инженеры по эксплуатации/оборудованию, первая линия техподдержки, ОТК/КИП.
- Свободный/разговорный английский (B2, C1, Upper-Intermediate) заявлен как ОБЯЗАТЕЛЬНОЕ
  требование. Если английский "будет плюсом", "желателен", "технический для чтения доков" —
  это НЕ повод для отказа, отвечай YES.
- Автоматизация как ОСНОВНАЯ задача на языке, которого у меня нет: Java, Python, C#, Kotlin,
  Ruby, Go, PHP. ВАЖНО: JavaScript и TypeScript — мои языки, на них я автоматизирую сам.
  Вакансии SDET / QA Automation на JS/TS (Playwright, Cypress, WebdriverIO) мне ПОДХОДЯТ.
  Если чужой язык лишь "будет плюсом" или это в основном ручное тестирование — это НЕ отказ.
- Основная специализация — нагрузочное/performance-тестирование, тестирование безопасности,
  embedded или 1С. (Если это лишь одна из задач среди обычного функционального QA — не отказ.)

Вакансия:
Название: {vacancy_title}
Описание: {vacancy_description}

Ответь РОВНО одним словом, без пояснений:
YES — если подходит (или если сомневаешься).
NO — только при явном дисквалификаторе выше.
"""
    
    # deterministic=True — это бинарный классификатор, а не творческая задача.
    # На дефолтной температуре одна и та же вакансия давала то YES, то NO.
    #
    # Если модель не ответила, complete_with_retry бросает ProviderError и мы его
    # НЕ глушим. Вернуть False нельзя: вызывающий код пометил бы вакансию
    # обработанной (add_applied_job) и больше никогда к ней не вернулся. Исключение
    # же означает «разберём на следующем круге».
    answer = await complete_with_retry(prompt, deterministic=True, timeout=120)
    return "YES" in answer.strip().upper()
