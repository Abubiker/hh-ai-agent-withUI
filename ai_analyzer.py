from settings import settings
from llm_providers import complete_with_retry, ProviderError


async def generate_cover_letter(vacancy_title: str, vacancy_description: str) -> str:
    MY_RESUME_SUMMARY = settings.resume_summary
    prompt = f"""
Напиши сопроводительное письмо для отклика на вакансию.
Мой профиль:
{MY_RESUME_SUMMARY}

Вакансия: {vacancy_title}
Описание: {vacancy_description}

КРИТИЧЕСКИЕ ПРАВИЛА (СТРОГО СОБЛЮДАТЬ):
1. ПИСАТЬ СТРОГО ТОЛЬКО НА РУССКОМ ЯЗЫКЕ! Никакого английского текста.
2. Пиши развернуто, структурировано (3-4 абзаца).
3. Стиль: живой, профессиональный, уверенный.
4. Включай в письмо мой стек и инструменты, а также конкретные достижения с цифрами — бери и то, и другое ТОЛЬКО из моего профиля выше.
5. Соотнеси мой опыт с тем, что требуется именно в этой вакансии.
6. НИКОГДА не выдумывай факты, которых нет в моем профиле: не приписывай мне образование, языки программирования, инструменты, сертификаты, уровень английского или годы опыта. Если чего-то в профиле нет — этого нет и в письме.
7. ВРЕМЯ ГЛАГОЛОВ. Определи по профилю, где я работаю СЕЙЧАС (обычно там сказано "по настоящее время" или указан только год начала). О текущем месте пиши строго в настоящем времени: "сейчас работаю", "занимаюсь", "отвечаю за". Формулировки "работал", "в последнее время я работал", "на прошлом месте" применительно к текущей работе — грубая фактическая ошибка. В прошедшем времени пиши только о предыдущих местах.
8. Никаких подписей в начале письма! Только в самом конце.
9. Подпись — одно только имя из моего профиля, БЕЗ фамилии. Никаких "С уважением". Если имени в профиле нет, не подписывайся вовсе.
10. ВЫВОДИ ТОЛЬКО ТЕКСТ ПИСЬМА БЕЗ КАВЫЧЕК. Твой ответ копируется автоматически! Строго запрещены любые вводные фразы (например, "Here is a sample...", "Вот письмо:"). Ни слова, кроме самого письма.

СТРУКТУРА ПИСЬМА (следуй ей, но факты бери только из профиля):
Строка 1: "Здравствуйте!"
Абзац 1: чем заинтересовала вакансия {vacancy_title} + кто я по профилю и сколько лет опыта.
Абзац 2: где работаю сейчас и что там делаю, с цифрами; затем предыдущий опыт в прошедшем времени.
Абзац 3: стек, инструменты и рабочие процессы — перечислением.
Абзац 4: готовность к тестовому заданию и собеседованию.
Последняя строка: имя.
"""
    
    try:
        # deterministic=False: письму нужна живость, в отличие от классификатора.
        text = await complete_with_retry(prompt, deterministic=False, timeout=180)
        # Жесткая очистка от частых галлюцинаций LLM
        text = text.replace('"', '').replace("'", "")
        if "Here is" in text or "Here's" in text:
            text = text.split("\n\n", 1)[-1]
        if "Note:" in text:
            text = text.split("Note:")[0].strip()
        return text.strip()
    except ProviderError as e:
        print(f"Ошибка при обращении к модели (письмо): {e}")
        return "Здравствуйте! Прошу рассмотреть мое резюме на эту вакансию. Буду рад обсудить детали на собеседовании."

async def is_vacancy_suitable(vacancy_title: str, vacancy_description: str) -> bool:
    MY_RESUME_SUMMARY = settings.resume_summary
    EXCLUSIONS = settings.exclusions
    prompt = f"""
Твоя задача — оценить, подходит ли вакансия под мои критерии поиска.
Мои требования и профиль (внимательно учти желаемую зарплату, локацию и стек технологий):
{MY_RESUME_SUMMARY}

ГЛАВНЫЙ ПРИНЦИП: определи мою профессию по профилю выше. Если вакансия из этой же
профессии — по умолчанию она мне ПОДХОДИТ (YES). Отклоняй (NO) только при ЯВНОМ,
чётко написанном в вакансии дисквалификаторе из списка ниже. Если сомневаешься или
чего-то не хватает в описании — отвечай YES: лишний отклик дешевле упущенной вакансии.

ВАЖНО ПРО ГРЕЙД: старшие позиции мне ПОДХОДЯТ. Senior, Сеньор, Старший, Ведущий —
на такие вакансии отвечай YES, я готов пробовать себя на них. Не отклоняй вакансию
только за слово Senior или «старший» в названии.

Отклоняй (NO) ТОЛЬКО если в вакансии ПРЯМО указано что-то из этого:
{EXCLUSIONS}

Отдельно: ревью работы коллег, наставничество для младших и участие в собеседованиях
управлением НЕ считаются — это обычные задачи старшего специалиста, таким вакансиям YES.

Вакансия:
Название: {vacancy_title}
Описание: {vacancy_description}

Ответь РОВНО одним словом, без пояснений:
YES — если подходит (или если сомневаешься).
NO — только при явном дисквалификаторе выше.
"""
    
    # deterministic=True — это бинарный классификатор, а не творческая задача.
    # На дефолтной температуре одна и та же вакансия давала то YES, то NO.
    #
    # Если модель не ответила, complete_with_retry бросает ProviderError и мы его
    # НЕ глушим. Вернуть False нельзя: вызывающий код пометил бы вакансию
    # обработанной (add_applied_job) и больше никогда к ней не вернулся. Исключение
    # же означает «разберём на следующем круге».
    answer = await complete_with_retry(prompt, deterministic=True, timeout=120)
    return "YES" in answer.strip().upper()
