"""Старый способ хранения настроек. Оставлен только ради переноса.

Настройки давно живут в settings.json (см. settings.py) и правятся в окне
приложения. Этот файл читается ровно один раз — при первом запуске, если
settings.json ещё нет, — чтобы перенести значения из прежних версий агента.

Личных данных здесь быть не должно: файл лежит в репозитории и попадает
в архив с исходниками, который передают другим людям. Своё резюме, запросы
и токены заполняйте в окне приложения либо в .env.
"""
import os
from dotenv import load_dotenv

# Загружаем переменные окружения из .env файла
load_dotenv()

# Telegram
TG_BOT_TOKEN = os.getenv("TG_BOT_TOKEN", "YOUR_BOT_TOKEN_HERE")
TG_USER_ID = os.getenv("TG_USER_ID", "YOUR_USER_ID_HERE")

# Ollama (локальная модель)
OLLAMA_URL = os.getenv("OLLAMA_URL", "http://localhost:11434/api/generate")
OLLAMA_MODEL = os.getenv("OLLAMA_MODEL", "llama3")

# Ключевые слова для поиска. Запросы намеренно узкие — только название
# должности. Ищем ТОЛЬКО по названию вакансии (SEARCH_IN_TITLE_ONLY ниже),
# поэтому короткие запросы работают точно: "Тестировщик" поймает и
# "Тестировщик ПО", и "Старший тестировщик". Широкие запросы вроде
# "Функциональное тестирование" цепляют вакансии, где эти слова лишь
# в описании, — оттуда в выдачу лез посторонний мусор.
SEARCH_QUERIES = [
    "Тестировщик",
    "QA",
]

# Искать слова запроса только в НАЗВАНИИ вакансии, а не в описании и названии
# компании. Именно из-за поиска по описанию в выдачу лезли посторонние вакансии.
SEARCH_IN_TITLE_ONLY = True

# Сколько страниц выдачи разбирать по каждому запросу за один проход.
# Без ограничения агент уходил вглубь первого же запроса на сотни вакансий
# и до остальных просто не доходил за сеанс. Свежие вакансии всё равно
# наверху — сортировка по дате публикации.
MAX_PAGES_PER_QUERY = 2

# Пауза между проходами, в минутах. Вакансии появляются постепенно, а частые
# обходы повышают риск блокировки со стороны hh.ru.
CYCLE_PAUSE_MINUTES = 10

# Название резюме, которым агент откликается. Должно в точности совпадать
# с заголовком резюме на hh.ru.
TARGET_RESUME_NAME = ""

# Текст о себе для сопроводительных писем. Модель пишет письма строго по нему
# и ничего не выдумывает: чего здесь нет, того не будет и в письмах.
# Заполняется в окне приложения, вкладка «Резюме».
MY_RESUME_SUMMARY = ""
