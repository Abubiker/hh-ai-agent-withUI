import os
from dotenv import load_dotenv

# Загружаем переменные окружения из .env файла
load_dotenv()

# Telegram
TG_BOT_TOKEN = os.getenv("TG_BOT_TOKEN", "YOUR_BOT_TOKEN_HERE")
TG_USER_ID = os.getenv("TG_USER_ID", "YOUR_USER_ID_HERE")

# Ollama (локальная модель)
OLLAMA_URL = os.getenv("OLLAMA_URL", "http://localhost:11434/api/generate")
OLLAMA_MODEL = os.getenv("OLLAMA_MODEL", "llama3") # Укажите используемую модель

# HH.ru настройки
# Ключевые слова для поиска (QA / тестирование)
# Запросы намеренно узкие — только названия должности, как в моём резюме.
# Ищем ТОЛЬКО по названию вакансии (SEARCH_IN_TITLE_ONLY ниже), поэтому
# короткие запросы работают точно: "Тестировщик" поймает и "Тестировщик ПО",
# и "Старший тестировщик"; "QA" — и "QA Engineer", и "Fullstack QA".
# Широкие запросы вроде "Функциональное тестирование" убраны: они цепляли
# вакансии, где эти слова были лишь в описании (Media Buyer и прочий мусор).
SEARCH_QUERIES = [
    "Тестировщик",
    "QA",
    "Инженер по тестированию",
    "Специалист по тестированию",
]

# Искать слова запроса только в НАЗВАНИИ вакансии, а не в описании и названии
# компании. Именно из-за поиска по описанию в выдачу лезли посторонние вакансии.
SEARCH_IN_TITLE_ONLY = True

# Сколько страниц выдачи разбирать по каждому запросу за один круг.
# Без ограничения агент уходил вглубь первого же запроса на сотни вакансий
# и до остальных запросов просто не доходил за сеанс. Свежие вакансии всё
# равно наверху — сортировка по дате публикации.
MAX_PAGES_PER_QUERY = 2

# Пауза между кругами поиска, в минутах. "Круг" — это полный проход по всем
# запросам из SEARCH_QUERIES. Он занимает пару минут, после чего агент ждёт
# появления новых вакансий. Раньше пауза была жёстко 30 минут, из-за чего
# за часовой сеанс агент работал ~3 минуты, а остальное время спал.
CYCLE_PAUSE_MINUTES = 10
# Название резюме, которое агент должен выбирать при отклике (должно в точности совпадать с тем, что написано на HH)
TARGET_RESUME_NAME = "Тестировщик"

# Резюме (для генерации сопроводительного письма)
MY_RESUME_SUMMARY = ""
